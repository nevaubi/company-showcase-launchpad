import { loadReportInputs } from "@/lib/reports/inputs.server";
import { generateReportContent } from "@/lib/reports/generate.server";
import { normalizeOptions } from "@/lib/reports/kinds";
const t = process.argv[2] ?? "NVDA"; const kind = (process.argv[3] ?? "primer") as any;
const t0 = Date.now();
