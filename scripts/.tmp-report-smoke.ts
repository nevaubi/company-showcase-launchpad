console.log("generated", Date.now() - t0, "ms", c.title, "|", c.subtitle);
console.log(JSON.stringify(c.qa, null, 1).slice(0, 1500));
await Bun.write(`/tmp/rep/${t}-${kind}.json`, JSON.stringify(c, null, 1));
