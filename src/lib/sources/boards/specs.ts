/**
 * The curated tiles of "What the data says" and the boards that hold them. Every tile names its dataset by
 * id and was computed once from production rows on 25 Nov 2026 (the boards report lists each headline with
 * its period and snapshot). A tile reads only what the reads allow without migration 0069: a whole small
 * snapshot, an indexed key, a cell filter on a snapshot of at most 50,000 rows, or one period's cross-section.
 *
 * Subjects and titles use the publisher's own words; notes state a caveat the publisher or the store states
 * (adjustment, cohort, an unpublished month). Nothing here is a model's sentence.
 */
