const FRED_NOTE_SA = "Seasonally adjusted. FRED copy of the publisher's series.";
const FRED_NOTE_NSA = "Not seasonally adjusted. FRED copy of the publisher's series.";
const FRED_NOTE_SAAR = "Seasonally adjusted annual rate. FRED copy of the publisher's series.";

const fred = (
  spec: Omit<SeriesTileSpec, "series" | "measure" | "form"> & { code: string; form?: SeriesTileSpec["form"] },
): SeriesTileSpec => {
  const { code, form, ...rest } = spec;
  return { ...rest, measure: code, series: { whole: true }, form: form ?? "line" };
};

const mer = (
  spec: Omit<SeriesTileSpec, "series" | "measure" | "form" | "collection" | "subjectCheck"> & { msn: string; description: string },
): SeriesTileSpec => {
  const { msn, description, ...rest } = spec;
  return {
    ...rest,
    collection: "04_energy",
    measure: "Value",
    series: { where: [{ field: "MSN", value: msn }] },
    subjectCheck: { field: "Description", value: description },
    form: "line",
  };
};

