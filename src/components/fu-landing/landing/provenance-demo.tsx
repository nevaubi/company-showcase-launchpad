const PDF_W = 612;
const PDF_H = 792;
const PRECEDENT_COLORS = ["#2f5bd3", "#c2410c"];

/** The cells the guided tour clicks, in order. */
const TOUR: CellRef[] = [
  { r: 11, c: "F" },
  { r: 8, c: "F" },
  { r: 15, c: "F" },
  { r: 23, c: "F" },
  { r: 26, c: "F" },
  { r: 12, c: "E" },
  { r: 11, c: "G" },
];

const easeInOutCubic = (t: number) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
const sameRef = (a: CellRef | null, b: CellRef | null) => !!a && !!b && a.r === b.r && a.c === b.c;

