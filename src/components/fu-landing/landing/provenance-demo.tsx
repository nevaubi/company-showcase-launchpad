export function ProvenanceSection({ id = "provenance" }: { id?: string }) {
  const [selected, setSelected] = useState<CellRef>(TOUR[0]);
  const [token, setToken] = useState(0);
  const [arrived, setArrived] = useState(-1);
  const [touring, setTouring] = useState(true);
  const [cursor, setCursor] = useState<{ x: number; y: number; click: number } | null>(null);
  const stageRef = useRef<HTMLDivElement>(null);
  const gridRef = useRef<HTMLDivElement>(null);
  const pdfScrollRef = useRef<HTMLDivElement>(null);
  const highlightRef = useRef<HTMLDivElement>(null);
  const cellRefs = useRef(new Map<string, HTMLElement>());
  const inView = useInView(stageRef, { amount: 0.35 });
  const tourIndex = useRef(0);

  const info = useMemo(() => cellInfo(selected), [selected]);

  const select = useCallback((ref: CellRef, viaUser: boolean) => {
    if (viaUser) {
      setTouring(false);
      setCursor(null);
    }
    setSelected(ref);
    setToken((t) => t + 1);
  }, []);

  // Keep a cell visible inside the grid without moving the page.
  const revealCell = useCallback((ref: CellRef) => {
    const el = cellRefs.current.get(addr(ref));
    const grid = gridRef.current;
    if (!el || !grid) return;
    const er = el.getBoundingClientRect();
    const gr = grid.getBoundingClientRect();
    const head = 26;
    const frozen = 34 + 196;
    if (er.top < gr.top + head) grid.scrollTop -= gr.top + head - er.top + 8;
    else if (er.bottom > gr.bottom) grid.scrollTop += er.bottom - gr.bottom + 8;
    if (ref.c !== "A" && er.left < gr.left + frozen) grid.scrollLeft -= gr.left + frozen - er.left + 8;
    else if (er.right > gr.right) grid.scrollLeft += er.right - gr.right + 8;
  }, []);

  useEffect(() => { revealCell(selected); }, [selected, revealCell]);

  // Guided tour: an agent cursor glides to the next cell, clicks it, then waits for the reader to settle.
  useEffect(() => {
    if (!touring || !inView) return;
    let cancelled = false;
    const timers: number[] = [];
    const run = () => {
      if (cancelled) return;
      tourIndex.current = (tourIndex.current + 1) % TOUR.length;
      const ref = TOUR[tourIndex.current];
      revealCell(ref);
      const el = cellRefs.current.get(addr(ref));
      const stage = stageRef.current;
      if (el && stage) {
        const s = stage.getBoundingClientRect();
        const r = el.getBoundingClientRect();
        setCursor((c) => ({ x: r.left - s.left + r.width * 0.55, y: r.top - s.top + r.height * 0.6, click: c?.click ?? 0 }));
      }
      timers.push(window.setTimeout(() => {
        if (cancelled) return;
        setCursor((c) => (c ? { ...c, click: c.click + 1 } : c));
        select(ref, false);
      }, 750));
      timers.push(window.setTimeout(run, 4300));
    };
    // Place the cursor on the first cell immediately.
    revealCell(TOUR[tourIndex.current]);
    const first = cellRefs.current.get(addr(TOUR[tourIndex.current]));
    const stage = stageRef.current;
    if (first && stage) {
      const s = stage.getBoundingClientRect();
      const r = first.getBoundingClientRect();
      setCursor({ x: r.left - s.left + r.width * 0.55, y: r.top - s.top + r.height * 0.6, click: 0 });
    }
    timers.push(window.setTimeout(run, 3600));
    return () => {
      cancelled = true;
      timers.forEach((t) => window.clearTimeout(t));
    };
  }, [touring, inView, select, revealCell]);

  const replay = () => {
    tourIndex.current = 0;
    setSelected(TOUR[0]);
    setToken((t) => t + 1);
    setTouring(true);
  };

  const from = useCallback(() => ({ el: cellRefs.current.get(addr(selected)) ?? null, clip: gridRef.current }), [selected]);
  const to = useCallback(() => ({ el: highlightRef.current, clip: pdfScrollRef.current }), []);

  return (
    <section id={id} className={styles.section} aria-labelledby={`${id}-title`}>
      <div className={styles.wrap}>
        <div className={styles.head}>
          <p className={styles.kicker}><span>01</span><i aria-hidden="true" />Provenance</p>
          <h2 id={`${id}-title`} className={styles.title}>
            Each figure opens<br /><em>at its source line.</em>
          </h2>
          <div className={styles.headSide}>
            <p>
              FiledUnder builds the model from the filing and keeps the link. Click any cell and the source document scrolls to the exact line it came from. Derived cells trace back through their inputs to the figure the company reported.
            </p>
            <button type="button" className={styles.replay} onClick={replay} aria-pressed={touring}>
              {touring ? <><MousePointer2 size={14} aria-hidden="true" /> Guided tour running</> : <><RotateCcw size={14} aria-hidden="true" /> Replay guided tour</>}
            </button>
          </div>
        </div>

        <div ref={stageRef} className={styles.stage}>
          <Sheet selected={selected} info={info} onSelect={select} cellRefs={cellRefs} gridRef={gridRef} />
          <Reader info={info} token={token} onArrive={setArrived} scrollRef={pdfScrollRef} highlightRef={highlightRef} />
          <Connector stageRef={stageRef} from={from} to={to} visible={arrived === token} token={token} />
          <AnimatePresence>
            {touring && cursor && (
              <motion.div
                className={styles.agentCursor}
                initial={{ opacity: 0, x: cursor.x, y: cursor.y }}
                animate={{ opacity: 1, x: cursor.x, y: cursor.y }}
                exit={{ opacity: 0 }}
                transition={{ type: "spring", stiffness: 120, damping: 20, mass: 0.9 }}
                aria-hidden="true"
              >
                <svg width="18" height="18" viewBox="0 0 24 24"><path d="M4 3l7.5 18 2.6-7.4L21.5 11z" /></svg>
                <span className={styles.agentTag}>FiledUnder</span>
                <AnimatePresence>
                  <motion.span
                    key={cursor.click}
                    className={styles.clickRing}
                    initial={{ scale: 0.2, opacity: cursor.click ? 0.7 : 0 }}
                    animate={{ scale: 1.8, opacity: 0 }}
                    transition={{ duration: 0.6, ease: "easeOut" }}
                  />
                </AnimatePresence>
              </motion.div>
            )}
          </AnimatePresence>
        </div>

        <Details info={info} />
        <p className={styles.footnote}>
          Source: {SOURCE_DOC.company}, {SOURCE_DOC.title}. PDF from the company's investor relations site; filed with the SEC on {SOURCE_DOC.filed} as {SOURCE_DOC.exhibit} to Form {SOURCE_DOC.form}. Every value in the model was matched against the PDF text.
        </p>
      </div>
    </section>
  );
}

