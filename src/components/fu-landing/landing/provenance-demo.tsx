function Connector({ stageRef, from, to, visible, token }: {
  stageRef: React.RefObject<HTMLDivElement | null>;
  from: () => { el: HTMLElement | null; clip: HTMLElement | null };
  to: () => { el: HTMLElement | null; clip: HTMLElement | null };
  visible: boolean;
  token: number;
}) {
  const pathRef = useRef<SVGPathElement>(null);
  const aRef = useRef<SVGCircleElement>(null);
  const bRef = useRef<SVGCircleElement>(null);
  const gRef = useRef<SVGGElement>(null);

  useEffect(() => {
    let raf = 0;
    const inside = (r: DOMRect, c: DOMRect, y: number) => y >= c.top - 1 && y <= c.bottom + 1 && r.right > c.left - 1 && r.left < c.right + 1;
    const tick = () => {
      const stage = stageRef.current;
      const f = from();
      const t = to();
      const g = gRef.current;
      if (stage && g && f.el && t.el && f.clip && t.clip && visible) {
        const s = stage.getBoundingClientRect();
        const fr = f.el.getBoundingClientRect();
        const tr = t.el.getBoundingClientRect();
        const fc = f.clip.getBoundingClientRect();
        const tc = t.clip.getBoundingClientRect();
        const x1 = fr.right - s.left;
        const y1 = fr.top + fr.height / 2 - s.top;
        const x2 = tr.left - s.left;
        const y2 = tr.top + tr.height / 2 - s.top;
        const ok = inside(fr, fc, fr.top + fr.height / 2) && inside(tr, tc, tr.top + tr.height / 2) && x2 > x1 + 20;
        g.style.opacity = ok ? "1" : "0";
        if (ok) {
          const dx = Math.max(40, (x2 - x1) * 0.45);
          pathRef.current?.setAttribute("d", `M ${x1} ${y1} C ${x1 + dx} ${y1}, ${x2 - dx} ${y2}, ${x2} ${y2}`);
          aRef.current?.setAttribute("cx", String(x1));
          aRef.current?.setAttribute("cy", String(y1));
          bRef.current?.setAttribute("cx", String(x2));
          bRef.current?.setAttribute("cy", String(y2));
        }
      } else if (g) {
        g.style.opacity = "0";
      }
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [from, to, stageRef, visible]);

  return (
    <svg className={styles.connector} aria-hidden="true">
      <g ref={gRef} style={{ opacity: 0, transition: "opacity .2s" }}>
        <motion.path
          key={token}
          ref={pathRef}
          fill="none"
          initial={{ pathLength: 0 }}
          animate={{ pathLength: visible ? 1 : 0 }}
          transition={{ duration: 0.45, ease: "easeOut" }}
        />
        <circle ref={aRef} r={3.5} />
        <circle ref={bRef} r={3.5} />
      </g>
    </svg>
  );
}

