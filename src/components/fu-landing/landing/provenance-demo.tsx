interface ReaderProps {
  info: CellInfo;
  token: number;
  onArrive: (token: number) => void;
  scrollRef: React.RefObject<HTMLDivElement | null>;
  highlightRef: React.RefObject<HTMLDivElement | null>;
}

function Reader({ info, token, onArrive, scrollRef, highlightRef }: ReaderProps) {
  const pageRefs = useRef<(HTMLDivElement | null)[]>([]);
  const anim = useRef<number | null>(null);
  const [zoom, setZoom] = useState(1.25);
  useEffect(() => { if (window.matchMedia("(max-width: 700px)").matches) setZoom(2.25); }, []);
  const [currentPage, setCurrentPage] = useState(1);
  const [arrivedToken, setArrivedToken] = useState(-1);
  const target = info.target;
  const targetPage = target?.row.page ?? 1;
  const targetCell = target ? target.row.cells.find((c) => c.q === target.q) : undefined;

  const cancel = useCallback(() => {
    if (anim.current) cancelAnimationFrame(anim.current);
    anim.current = null;
  }, []);

  const scrollToTarget = useCallback((smooth: boolean) => {
    const sc = scrollRef.current;
    const pageEl = pageRefs.current[targetPage - 1];
    if (!sc || !pageEl || !targetCell) return;
    const [, top, , bottom] = targetCell.box;
    const yInPage = ((top + bottom) / 2 / PDF_H) * pageEl.offsetHeight;
    const destY = Math.max(0, Math.min(sc.scrollHeight - sc.clientHeight, pageEl.offsetTop + yInPage - sc.clientHeight * 0.45));
    const [x0, , x1] = targetCell.box;
    const xInPage = ((x0 + x1) / 2 / PDF_W) * pageEl.offsetWidth;
    const destX = Math.max(0, Math.min(sc.scrollWidth - sc.clientWidth, pageEl.offsetLeft + xInPage - sc.clientWidth * 0.7));
    cancel();
    const fromY = sc.scrollTop;
    const fromX = sc.scrollLeft;
    const dist = Math.abs(destY - fromY);
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (!smooth || reduce || dist < 2) {
      sc.scrollTop = destY;
      sc.scrollLeft = destX;
      setArrivedToken(token);
      onArrive(token);
      return;
    }
    const duration = Math.min(1300, Math.max(520, 380 + dist * 0.12));
    const start = performance.now();
    const step = (now: number) => {
      const t = Math.min(1, (now - start) / duration);
      const e = easeInOutCubic(t);
      sc.scrollTop = fromY + (destY - fromY) * e;
      sc.scrollLeft = fromX + (destX - fromX) * e;
      if (t < 1) anim.current = requestAnimationFrame(step);
      else {
        anim.current = null;
        setArrivedToken(token);
        onArrive(token);
      }
    };
    setArrivedToken(-1);
    anim.current = requestAnimationFrame(step);
  }, [cancel, onArrive, scrollRef, targetCell, targetPage, token]);

  useEffect(() => {
    scrollToTarget(true);
    return cancel;
    // token changes on every selection, including re-selecting the same cell
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [token]);

  useLayoutEffect(() => {
    scrollToTarget(false);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [zoom]);

  useEffect(() => {
    const sc = scrollRef.current;
    if (!sc) return;
    const stop = () => cancel();
    const onScroll = () => {
      const mid = sc.scrollTop + sc.clientHeight / 2;
      let p = 1;
      pageRefs.current.forEach((el, i) => { if (el && el.offsetTop <= mid) p = i + 1; });
      setCurrentPage(p);
    };
    sc.addEventListener("wheel", stop, { passive: true });
    sc.addEventListener("touchstart", stop, { passive: true });
    sc.addEventListener("scroll", onScroll, { passive: true });
    onScroll();
    return () => {
      sc.removeEventListener("wheel", stop);
      sc.removeEventListener("touchstart", stop);
      sc.removeEventListener("scroll", onScroll);
    };
  }, [cancel, scrollRef]);

  const pct = (v: number, of: number) => `${(v / of) * 100}%`;

  return (
    <div className={styles.readerWin}>
      <div className={styles.readerBar}>
        <PanelLeft size={15} aria-hidden="true" className={styles.dim} />
        <FileText size={15} aria-hidden="true" />
        <span className={styles.fileName}>{SOURCE_DOC.file}</span>
        <span className={styles.pageBox}>
          <span className={styles.pageNum} aria-live="polite">{currentPage}</span>
          <span className={styles.dim}>of {SOURCE_DOC.pageCount}</span>
        </span>
        <span className={styles.vsep} />
        <span className={styles.zoom}>
          <button type="button" aria-label="Zoom out" onClick={() => setZoom((z) => Math.max(0.75, +(z - 0.25).toFixed(2)))} disabled={zoom <= 0.75}><Minus size={13} /></button>
          <span>{Math.round(zoom * 100)}%</span>
          <button type="button" aria-label="Zoom in" onClick={() => setZoom((z) => Math.min(2.5, +(z + 0.25).toFixed(2)))} disabled={zoom >= 2.5}><Plus size={13} /></button>
        </span>
        <span className={styles.vsep} />
        <span className={styles.search}>
          <Search size={13} aria-hidden="true" />
          <span>{targetCell?.text ?? ""}</span>
          <span className={styles.dim}>1/1</span>
        </span>
      </div>
      <div ref={scrollRef} className={styles.canvas} tabIndex={0} aria-label={`${SOURCE_DOC.title}, PDF`}>
        <div className={styles.pages} style={{ width: `calc((100% - 48px) * ${zoom})` }}>
          {pdfPages.map(([w, h], i) => {
            const n = i + 1;
            const isTarget = n === targetPage && !!targetCell;
            return (
              <div
                key={n}
                ref={(el) => { pageRefs.current[i] = el; }}
                className={styles.page}
                style={{ aspectRatio: `${w} / ${h}` }}
                data-page={n}
              >
                <img
                  src={assetUrl(`page-${String(n).padStart(2, "0")}.webp`)}
                  alt={n === targetPage ? `Page ${printedPage(n)} of the supplement: ${target?.row.table}` : ""}
                  loading={Math.abs(n - targetPage) <= 2 || n <= 2 ? "eager" : "lazy"}
                  decoding="async"
                  draggable={false}
                />
                {isTarget && target && targetCell && (
                  <>
                    <motion.div
                      key={`row-${token}`}
                      className={styles.rowBand}
                      style={{
                        left: pct(target.row.rowBox[0] - 6, PDF_W),
                        top: pct(targetCell.box[1] - 3.2, PDF_H),
                        width: pct(target.row.rowBox[2] - target.row.rowBox[0] + 12, PDF_W),
                        height: pct(targetCell.box[3] - targetCell.box[1] + 6.4, PDF_H),
                      }}
                      initial={{ opacity: 0 }}
                      animate={{ opacity: arrivedToken === token ? 1 : 0 }}
                      transition={{ duration: 0.35 }}
                    />
                    <motion.div
                      key={`hl-${token}`}
                      ref={highlightRef}
                      className={styles.highlight}
                      style={{
                        left: pct(targetCell.box[0] - 4, PDF_W),
                        top: pct(targetCell.box[1] - 3, PDF_H),
                        width: pct(targetCell.box[2] - targetCell.box[0] + 8, PDF_W),
                        height: pct(targetCell.box[3] - targetCell.box[1] + 6, PDF_H),
                      }}
                      initial={{ opacity: 0, scale: 1.6 }}
                      animate={arrivedToken === token ? { opacity: 1, scale: 1 } : { opacity: 0, scale: 1.6 }}
                      transition={{ type: "spring", stiffness: 420, damping: 30 }}
                    >
                      {arrivedToken === token && <span className={styles.pulse} aria-hidden="true" />}
                    </motion.div>
                  </>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

