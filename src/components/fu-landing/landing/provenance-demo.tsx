function Details({ info }: { info: CellInfo }) {
  const t = info.target;
  if (!t) return null;
  const cell = t.row.cells.find((c) => c.q === t.q)!;
  const isDerived = info.kind !== "source";
  const fields = [
    { k: "Filing", v: `Form ${SOURCE_DOC.form}, ${SOURCE_DOC.exhibit}` },
    { k: "Accession", v: SOURCE_DOC.accession },
    { k: "Table", v: t.row.table },
    { k: "Row", v: t.row.pdfRow },
    { k: "Column", v: quarterColumnNames[t.q] },
    { k: "Page", v: `p. ${printedPage(t.row.page)} (PDF ${t.row.page} of ${SOURCE_DOC.pageCount})` },
  ];
  const checks = isDerived
    ? info.kind === "change"
      ? [`Inputs ${info.precedents.map(addr).join(" and ")} both cited`, "Same row, same table in both periods", "Recomputes on every new filing"]
      : [
          `Recomputed from ${info.precedents.map(addr).join(" and ")}`,
          `Reported ${cell.text}${info.unit === "pct" ? "%" : ""} on p. ${printedPage(t.row.page)}${info.kind === "calc" && info.display !== `${cell.text}%` ? ", within 0.01 pt rounding" : ""}`,
          "Both inputs cited to the statement of income",
        ]
    : ["Value matches document text", `Period aligned to ${quarterColumnNames[t.q]}`, info.unit === "pct" ? "Units: percent" : info.unit === "per_share" ? "Units: dollars per share" : "Units: $ in millions"];

  return (
    <AnimatePresence mode="wait">
      <motion.div
        key={`${addr(info.ref)}`}
        className={styles.details}
        initial={{ opacity: 0, y: 6 }}
        animate={{ opacity: 1, y: 0 }}
        exit={{ opacity: 0, y: -6 }}
        transition={{ duration: 0.22 }}
      >
        <div className={styles.detailHead}>
          <span className={styles.ticker}>{SOURCE_DOC.ticker}</span>
          <div>
            <b>{info.label}</b>
            <span>{addr(info.ref)} · {isDerived ? info.formula : `${cell.text} as printed`}</span>
          </div>
          <span className={styles.detailValue}>{info.display}</span>
        </div>
        <dl className={styles.fields}>
          {fields.map((f) => (
            <div key={f.k}><dt>{f.k}</dt><dd>{f.v}</dd></div>
          ))}
        </dl>
        <ul className={styles.checks}>
          {checks.map((c) => <li key={c}><Check size={13} aria-hidden="true" />{c}</li>)}
        </ul>
      </motion.div>
    </AnimatePresence>
  );
}

