interface SheetProps {
  selected: CellRef;
  info: CellInfo;
  onSelect: (ref: CellRef, viaUser: boolean) => void;
  cellRefs: React.MutableRefObject<Map<string, HTMLElement>>;
  gridRef: React.RefObject<HTMLDivElement | null>;
}

function Sheet({ selected, info, onSelect, cellRefs, gridRef }: SheetProps) {
  const precedentColor = (ref: CellRef) => {
    const i = info.precedents.findIndex((p) => sameRef(p, ref));
    return i >= 0 ? PRECEDENT_COLORS[i % PRECEDENT_COLORS.length] : undefined;
  };

  const onKeyDown = (e: React.KeyboardEvent) => {
    const ci = columns.indexOf(selected.c);
    let next: CellRef | null = null;
    if (e.key === "ArrowRight" && ci < columns.length - 1) next = { r: selected.r, c: columns[ci + 1] };
    if (e.key === "ArrowLeft" && ci > 0) next = { r: selected.r, c: columns[ci - 1] };
    if (e.key === "ArrowDown" && selected.r < sheetRows.length) next = { r: selected.r + 1, c: selected.c };
    if (e.key === "ArrowUp" && selected.r > 1) next = { r: selected.r - 1, c: selected.c };
    if (next) {
      e.preventDefault();
      onSelect(next, true);
    }
  };

  const sourcedCount = useMemo(() => sheetRows.filter((r) => r.kind === "source").length * quarterCols.length, []);

  return (
    <div className={styles.sheetWin}>
      <div className={styles.winBar}>
        <span className={styles.lights} aria-hidden="true"><i /><i /><i /></span>
        <span className={styles.xlIcon} aria-hidden="true">X</span>
        <span className={styles.winTitle}>BAC_3Q26_model.xlsx</span>
        <span className={styles.winMeta}>Generated by FiledUnder</span>
      </div>
      <div className={styles.ribbonTabs} aria-hidden="true">
        {["File", "Home", "Insert", "Formulas", "Data", "Review", "View"].map((t) => (
          <span key={t} data-active={t === "Home" || undefined}>{t}</span>
        ))}
      </div>
      <div className={styles.ribbon} aria-hidden="true">
        <span className={styles.fontBox}>Aptos <ChevronDown size={12} /></span>
        <span className={styles.fontBox} data-narrow>11 <ChevronDown size={12} /></span>
        <span className={styles.sep} />
        <Bold size={14} /><Italic size={14} /><Underline size={14} />
        <span className={styles.sep} />
        <AlignLeft size={14} />
        <span className={styles.sep} />
        <span className={styles.fontBox} data-wide>Number <ChevronDown size={12} /></span>
        <Percent size={14} />
        <span className={styles.sep} />
        <Sigma size={14} /><Filter size={14} />
      </div>
      <div className={styles.formulaBar}>
        <span className={styles.nameBox}>{addr(selected)}</span>
        <span className={styles.fx}>fx</span>
        <span className={styles.formula}>
          <span className={styles.formulaText}>{info.formula || " "}</span>
          {info.kind === "source" && info.target && (
            <span className={styles.citePill}>
              <FileText size={11} aria-hidden="true" />
              p.{printedPage(info.target.row.page)} · {info.target.row.pdfRow}
            </span>
          )}
        </span>
      </div>
      <div
        ref={gridRef}
        className={styles.grid}
        role="grid"
        aria-label="Generated model. Select a cell to open its source in the filing."
        aria-rowcount={sheetRows.length + 1}
        aria-colcount={columns.length + 1}
        tabIndex={0}
        onKeyDown={onKeyDown}
      >
        <div role="row" className={styles.colHeads}>
          <span className={styles.corner} />
          {columns.map((c) => (
            <span key={c} role="columnheader" data-col={c} data-active={selected.c === c || undefined}>{c}</span>
          ))}
        </div>
        {sheetRows.map((def, i) => {
          const r = i + 1;
          return (
            <div role="row" key={r} className={styles.row} data-kind={def.kind}>
              <span role="rowheader" className={styles.rowHead} data-active={selected.r === r || undefined}>{r}</span>
              {columns.map((c) => {
                const ref = { r, c };
                const ci = cellInfo(ref);
                const isSel = sameRef(ref, selected);
                const pColor = precedentColor(ref);
                const isHeader = def.kind === "header";
                const neg = (ci.kind === "change" && ci.display.startsWith("−"));
                const style = pColor ? ({ "--prec": pColor } as CSSProperties) : undefined;
                return (
                  <span
                    key={c}
                    ref={(el) => {
                      if (el) cellRefs.current.set(addr(ref), el);
                      else cellRefs.current.delete(addr(ref));
                    }}
                    role="gridcell"
                    aria-selected={isSel}
                    data-col={c}
                    data-kind={ci.kind}
                    data-sel={isSel || undefined}
                    data-prec={pColor ? true : undefined}
                    data-bold={(def.kind === "source" && def.bold) || isHeader || undefined}
                    data-neg={neg || undefined}
                    data-ok={(ci.kind === "check" && ci.display.startsWith("✓")) || undefined}
                    className={styles.cell}
                    style={style}
                    onMouseDown={(e) => {
                      e.preventDefault();
                      gridRef.current?.focus({ preventScroll: true });
                      onSelect(ref, true);
                    }}
                    title={ci.kind === "source" && ci.target ? `${ci.label}, ${ci.target.q}: open source on p.${printedPage(ci.target.row.page)}` : undefined}
                  >
                    {def.kind === "title" && c === "A" ? (
                      <span className={styles.titleCell}><b>{def.text}</b><em>{def.sub}</em></span>
                    ) : (
                      ci.display
                    )}
                    {ci.kind === "source" && <i className={styles.citeMark} aria-hidden="true" />}
                    {isSel && <i className={styles.fillHandle} aria-hidden="true" />}
                  </span>
                );
              })}
            </div>
          );
        })}
      </div>
      <div className={styles.sheetTabs}>
        <span className={styles.tabNav} aria-hidden="true"><ChevronLeft size={13} /><ChevronRight size={13} /></span>
        {["Model", "Segments", "Credit", "Sources"].map((t) => (
          <span key={t} className={styles.sheetTab} data-active={t === "Model" || undefined}>{t}</span>
        ))}
        <Plus size={13} aria-hidden="true" className={styles.tabPlus} />
      </div>
      <div className={styles.statusBar}>
        <span>Ready</span>
        <span>{sourcedCount} cited inputs</span>
        {info.kind === "source" && info.target && <span>Source: p.{printedPage(info.target.row.page)}</span>}
        {(info.kind === "calc" || info.kind === "change" || info.kind === "check") && <span>Formula · {info.precedents.length} precedents</span>}
      </div>
    </div>
  );
}

